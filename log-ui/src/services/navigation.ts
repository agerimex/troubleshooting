import { type LogRecord, type Report } from '@/types/report'
import { type ReportContext } from '@/types/stats'
import { sortedLogs } from '@/services/report'

// Navigation of the product blueprint (product-blueprint-v1.3): five pages,
// an execution viewer (Timeline & Sequence) that any page can open, and
// investigation links that resolve without the page they were copied from.

export type Page = 'logs' | 'executions' | 'problems' | 'releases' | 'settings'

export const PAGES: { value: Page, label: string }[] = [
  { value: 'logs', label: 'Log Analysis' },
  { value: 'executions', label: 'Timeline & Sequence' },
  { value: 'problems', label: 'Problems' },
  { value: 'releases', label: 'Releases' },
  { value: 'settings', label: 'Settings' }
]

export type ExecutionView = 'timeline' | 'sequence'

// Origin is where an execution was opened from: optional context with a
// return action, never part of the report's identity.
export interface Origin {
  page: Page
  label: string
}

// ExecutionTarget is one execution to open: a trace in an explicit window,
// with the evidence it was opened for selected.
export interface ExecutionTarget {
  traceId: string
  window: { from: string, to: string }
  spanId?: string
  recordId?: string
  // undefined: the saved preference, else Timeline.
  view?: ExecutionView
  origin?: Origin
  // The comparison an example was opened from (Releases).
  context?: ReportContext
}

export const VIEW_PREFERENCE_KEY = 'troubleshooting.execution.view'

// initialView: an explicit choice wins, then the saved preference, then
// Timeline (the blueprint's default).
export function initialView (explicit: ExecutionView | undefined, saved: string | null): ExecutionView {
  if (explicit) {
    return explicit
  }
  return saved === 'sequence' ? 'sequence' : 'timeline'
}

const traceIdPattern = /^[0-9a-f]{32}$/
const spanIdPattern = /^[0-9a-f]{16}$/
const nsPattern = /^-?\d{1,20}$/
// Record ids are generated by senders; only plain ids are carried in links.
const recordIdPattern = /^[\w.:-]{1,128}$/

// investigationHash is the hash route of an execution: non-sensitive
// identifiers only (no log bodies, no credentials, no origin state).
export function investigationHash (t: ExecutionTarget): string {
  const q = new URLSearchParams()
  q.set('trace', t.traceId)
  q.set('from', t.window.from)
  q.set('to', t.window.to)
  if (t.spanId) {
    q.set('span', t.spanId)
  }
  if (t.recordId && recordIdPattern.test(t.recordId)) {
    q.set('log', t.recordId)
  }
  if (t.view) {
    q.set('view', t.view)
  }
  return '#/executions?' + q.toString()
}

export function investigationLink (base: string, t: ExecutionTarget): string {
  return base.replace(/#.*$/, '') + investigationHash(t)
}

// parseRoute reads a hash route. '#/executions?trace=…' opens an execution;
// the legacy '#/investigate' and 'view=timing' are kept. Invalid identifiers
// open the page without an execution instead of guessing one.
export function parseRoute (hash: string): { page: Page, target: ExecutionTarget | null, error: string } {
  const m = /^#\/([a-z]+)(?:\?(.*))?$/.exec(hash)
  if (!m) {
    return { page: 'logs', target: null, error: '' }
  }
  const name = m[1] === 'investigate' || m[1] === 'investigations' ? 'executions' : m[1]
  const page = PAGES.some((p) => p.value === name) ? name as Page : 'logs'
  if (page !== 'executions' || !m[2]) {
    return { page, target: null, error: '' }
  }
  const q = new URLSearchParams(m[2])
  const traceId = (q.get('trace') ?? '').toLowerCase()
  const from = q.get('from') ?? ''
  const to = q.get('to') ?? ''
  if (!traceIdPattern.test(traceId) || !nsPattern.test(from) || !nsPattern.test(to) || BigInt(to) <= BigInt(from)) {
    return { page, target: null, error: 'The investigation link is incomplete or invalid: it needs a trace id of 32 hex digits and a window [from, to) in Unix nanoseconds.' }
  }
  const target: ExecutionTarget = { traceId, window: { from, to } }
  const span = (q.get('span') ?? '').toLowerCase()
  if (spanIdPattern.test(span)) {
    target.spanId = span
  }
  const log = q.get('log') ?? ''
  if (recordIdPattern.test(log)) {
    target.recordId = log
  }
  const view = q.get('view')
  if (view === 'sequence') {
    target.view = 'sequence'
  } else if (view === 'timeline' || view === 'timing') {
    target.view = 'timeline'
  }
  return { page, target, error: '' }
}

// --- Log Analysis: log rows inline under their exactly recorded span

// TraceLogs are the logs of one trace read for Log Analysis, with the span
// ids of the trace's loaded spans (to tell trace-level from unmatched logs).
export interface TraceLogs {
  status: 'ok' | 'unavailable'
  error: string
  logs: LogRecord[]
  spanIds: Set<string>
  truncated: boolean
  spansComplete: boolean
}

export function traceLogsOf (report: Report): TraceLogs {
  return {
    status: report.logs.status === 'ok' ? 'ok' : 'unavailable',
    error: report.logs.error ?? report.logs.status,
    logs: sortedLogs(report.logs.records),
    spanIds: new Set(report.spans.status === 'ok' ? report.spans.records.map((s) => s.spanId) : []),
    truncated: report.logs.truncated,
    spansComplete: report.spans.status === 'ok' && !report.spans.truncated
  }
}

// logsOfSpanId: the logs that recorded exactly this span of the trace. A
// bare span id or a timestamp never attaches a log.
export function logsOfSpanId (t: TraceLogs, spanId: string): LogRecord[] {
  return t.logs.filter((l) => l.spanId !== '' && l.spanId === spanId)
}

// Trace-level logs recorded no span; unmatched logs name a span that is not
// among the trace's loaded spans. Neither is placed under a guessed parent.
export function unattachedLogs (t: TraceLogs): { log: LogRecord, reason: string }[] {
  return t.logs
    .filter((l) => l.spanId === '' || !t.spanIds.has(l.spanId))
    .map((l) => ({
      log: l,
      reason: l.spanId === ''
        ? 'trace-level: no span recorded'
        : t.spansComplete ? 'span not found in this trace and window' : 'span not among the loaded spans'
    }))
}

// copyText copies to the clipboard; false means the caller must show the
// text for manual selection instead of claiming success.
export async function copyText (text: string): Promise<boolean> {
  try {
    if (!navigator.clipboard) {
      return false
    }
    await navigator.clipboard.writeText(text)
    return true
  } catch {
    return false
  }
}
